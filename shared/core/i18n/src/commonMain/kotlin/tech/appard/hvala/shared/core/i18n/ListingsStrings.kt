enum class ListingSortOrderId {
    NewestFirst,
    PriceAsc,
    PriceDesc,
}

fun ListingsStrings.sortOrderTitle(order: ListingSortOrderId): String = when (order) {
    ListingSortOrderId.NewestFirst -> sortNewestFirst
    ListingSortOrderId.PriceAsc -> sortPriceAsc
    ListingSortOrderId.PriceDesc -> sortPriceDesc
}
